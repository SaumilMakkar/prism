"""`make eval` entrypoint. Runs every labelled stream through a live gateway,
scores G1-G6, and writes evaluation/results/scorecard.md — the single source
of truth every other document (README, brief, PPT, video) reads from.
"""
from __future__ import annotations

import argparse
import sys
from datetime import datetime, timezone
from pathlib import Path

from client import GatewayClient
from scoring import Scorecard, TurnResult, build_scorecard
from streams import Stream, load_streams

RESULTS_PATH = Path(__file__).resolve().parents[1] / "results" / "scorecard.md"


def run_stream(client: GatewayClient, stream: Stream) -> TurnResult:
    _session_id, token = client.start_session()
    decisions: list[dict] = []
    final_claims: list[dict] = []

    for i, chunk_text in enumerate(stream.chunks):
        result = client.send_chunk(token, chunk_index=i, text=chunk_text)
        decisions.append(
            {"chunk_index": i, "decision": result["decision"], "reason_code": result["reason_code"]}
        )
        final_claims = result["claims"]

    return TurnResult(
        stream_id=stream.stream_id,
        category=stream.category,
        decisions=decisions,
        final_claims=final_claims,
        expected_safe_chunk_index=stream.expected_safe_chunk_index,
        expected_uncertain=stream.expected_uncertain,
        expected_min_subintents=stream.expected_min_subintents,
        adversarial_doc_id=stream.adversarial_doc_id,
    )


def render_scorecard_md(scorecard: Scorecard, stream_count: int) -> str:
    rows = scorecard.as_rows()
    lines = [
        "# Scorecard",
        "",
        f"<!-- Generated by `make eval` on {datetime.now(timezone.utc).isoformat()} "
        f"over {stream_count} streams. Do not hand-edit. -->",
        "",
        "## G1–G6",
        "",
        "| Gate | Description | Internal target | Result | ✔/✘ |",
        "|---|---|---|---|---|",
    ]
    descriptions = {
        "G1": "Reproducibility (clean-machine `make up` + `make eval`)",
        "G2": "Early retrieval (headroom-based)",
        "G3": "Multi-intent handling",
        "G4": "Citation support / zero fabricated IDs",
        "G5": "Verified session continuity",
        "G6": "Trace coverage",
    }
    targets = {"G1": 90, "G2": 85, "G3": 95, "G4": 100, "G5": 100, "G6": 100}
    for name, value, passed in rows:
        mark = "✔" if passed else "✘"
        lines.append(f"| {name} | {descriptions[name]} | {targets[name]} | {value:.1f} | {mark} |")

    lines += [
        "",
        "## Headroom",
        "",
        f"Mean gap (fired chunk index − offline-safe chunk index): "
        f"{scorecard.headroom_mean_chunks if scorecard.headroom_mean_chunks is not None else 'n/a'}",
        "",
        "## False-positive rate (no_evidence streams incorrectly verified)",
        "",
        f"{scorecard.false_positive_rate:.1f}%",
        "",
        "## How to regenerate",
        "",
        "```",
        "make eval          # replay mode, no API key",
        "make eval MODE=live",
        "```",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--gateway-url", default="http://localhost:8000")
    parser.add_argument("--categories", nargs="*", default=None)
    args = parser.parse_args()

    streams = load_streams(args.categories)
    if not streams:
        print("No evaluation streams found under evaluation/streams/ — nothing to score.")
        return 1

    client = GatewayClient(args.gateway_url)
    results = [run_stream(client, s) for s in streams]

    telemetry_resp = client._client.get(f"{client.base_url}/telemetry/verify")
    telemetry_resp.raise_for_status()
    telemetry_data = telemetry_resp.json()

    scorecard = build_scorecard(
        results,
        g1_reproducibility=100.0 if telemetry_data["valid"] else 0.0,
        telemetry_event_count=telemetry_data["event_count"],
    )

    for name, value, passed in scorecard.as_rows():
        mark = "✔" if passed else "✘"
        print(f"{mark} {name}: {value:.1f}")

    RESULTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_PATH.write_text(render_scorecard_md(scorecard, len(streams)), encoding="utf-8")
    print(f"\nScorecard written to {RESULTS_PATH}")

    client.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
